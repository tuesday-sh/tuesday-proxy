// 1. Map CPSC unit sales for known electronic/network models
const volumeMap = new Map();
for (const r of cpsc) {
  for (const prod of r.Products || []) {
    if (prod.NumberOfUnits) {
      const m = prod.NumberOfUnits.match(/(\d[\d,]*)/);
      if (m) {
        const units = parseInt(m[1].replace(/,/g, ""), 10);
        const text = (r.Title + " " + prod.Name + " " + (prod.Model || "")).toLowerCase();
        if (text.includes("wyze")) volumeMap.set("wyze", Math.max(units, volumeMap.get("wyze") || 0));
        if (text.includes("anker")) volumeMap.set("anker", Math.max(units, volumeMap.get("anker") || 0));
      }
    }
  }
}

